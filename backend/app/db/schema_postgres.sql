-- ============================================================================
-- BOOKBASE: the 3NF relational schema, as it runs on PostgreSQL / Supabase.
-- The API applies this file at startup, and every statement is safe to re-run.
-- It can also be pasted into the Supabase SQL Editor.
--
-- 1NF: every column holds one value per row (books.author is the known exception: co-authors
--      are stored as a comma-separated string).
-- 2NF: every table has a single-column primary key, so no partial dependencies can exist.
-- 3NF: non-key columns depend only on the key. A book's available copy count is not stored:
--      it is derived from book_copies. A return request stores its loan, not the borrower,
--      because the borrower follows from the loan.
-- ============================================================================

-- Patrons (students) and librarians.
CREATE TABLE IF NOT EXISTS users (
    user_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    enrollment_no TEXT UNIQUE NOT NULL,
    full_name TEXT NOT NULL,
    email TEXT UNIQUE NOT NULL,
    password_hash TEXT NOT NULL,
    role TEXT NOT NULL CHECK (role IN ('admin', 'member')),
    max_books_quota INTEGER DEFAULT 4 NOT NULL CHECK (max_books_quota > 0),
    outstanding_fines NUMERIC(10, 2) DEFAULT 0.00 NOT NULL CHECK (outstanding_fines >= 0.0),
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- A title: what every copy of a book has in common.
CREATE TABLE IF NOT EXISTS books (
    book_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    isbn TEXT UNIQUE NOT NULL,
    title TEXT NOT NULL,
    author TEXT NOT NULL,
    category TEXT NOT NULL,
    published_year INTEGER NOT NULL,
    description TEXT,
    cover_url TEXT NOT NULL,
    card_tint TEXT DEFAULT 'indigo' NOT NULL,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- One physical book. barcode is the unique code printed on its label.
CREATE TABLE IF NOT EXISTS book_copies (
    copy_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    book_id INTEGER NOT NULL REFERENCES books(book_id) ON DELETE CASCADE,
    barcode TEXT UNIQUE NOT NULL,
    shelf_location TEXT NOT NULL,
    status TEXT NOT NULL CHECK (status IN ('Available', 'Issued', 'Maintenance', 'Lost')),
    condition TEXT DEFAULT 'Good' NOT NULL,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- Links one physical copy to one student's profile for one borrowing, and records the copy's
-- condition when it left and when it came back, so damage can be traced to a specific loan.
CREATE TABLE IF NOT EXISTS circulation_loans (
    loan_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    copy_id INTEGER NOT NULL REFERENCES book_copies(copy_id) ON DELETE RESTRICT,
    user_id INTEGER NOT NULL REFERENCES users(user_id) ON DELETE RESTRICT,
    issue_date TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP NOT NULL,
    due_date TIMESTAMPTZ NOT NULL,
    return_date TIMESTAMPTZ NULL,
    fine_assessed NUMERIC(10, 2) DEFAULT 0.00 NOT NULL CHECK (fine_assessed >= 0.0),
    issued_via TEXT DEFAULT 'Direct Checkout' NOT NULL CHECK (issued_via IN ('Direct Checkout', 'Waitlist Auto-Fulfill')),
    condition_at_issue TEXT NOT NULL DEFAULT 'Good',
    condition_at_return TEXT NULL
);

-- A student asking to return a loan. It reaches the admin portal only once a student raises it.
CREATE TABLE IF NOT EXISTS return_requests (
    return_request_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    loan_id INTEGER NOT NULL REFERENCES circulation_loans(loan_id) ON DELETE CASCADE,
    reported_condition TEXT NOT NULL,
    notes TEXT,
    status TEXT NOT NULL DEFAULT 'Pending' CHECK (status IN ('Pending', 'Completed', 'Rejected')),
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP NOT NULL,
    resolved_at TIMESTAMPTZ NULL,
    resolved_by INTEGER REFERENCES users(user_id) ON DELETE SET NULL
);

-- The FIFO queue for a title with no copy available.
CREATE TABLE IF NOT EXISTS waitlist_reservations (
    reservation_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    book_id INTEGER NOT NULL REFERENCES books(book_id) ON DELETE CASCADE,
    user_id INTEGER NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    status TEXT NOT NULL CHECK (status IN ('Waiting', 'Fulfilled', 'Cancelled')),
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP NOT NULL,
    fulfilled_at TIMESTAMPTZ NULL
);

-- Students asking the library to acquire a title.
CREATE TABLE IF NOT EXISTS book_requests (
    request_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    book_id INTEGER REFERENCES books(book_id) ON DELETE SET NULL,
    title TEXT NOT NULL,
    author TEXT,
    category TEXT,
    notes TEXT,
    status TEXT NOT NULL DEFAULT 'Pending' CHECK (status IN ('Pending', 'Approved', 'Procured', 'Rejected')),
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- Every state-changing operation appends a row here.
CREATE TABLE IF NOT EXISTS db_audit_logs (
    log_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    operation_type TEXT NOT NULL,
    sql_summary TEXT NOT NULL,
    affected_entities TEXT NOT NULL,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- A copy can be on only one active loan: the database itself refuses a double booking.
CREATE UNIQUE INDEX IF NOT EXISTS idx_single_active_loan_per_copy
    ON circulation_loans(copy_id)
    WHERE return_date IS NULL;

-- A loan can have only one return request waiting for a librarian.
CREATE UNIQUE INDEX IF NOT EXISTS idx_single_pending_return_per_loan
    ON return_requests(loan_id)
    WHERE status = 'Pending';

-- Fast availability counts per title.
CREATE INDEX IF NOT EXISTS idx_copies_book_status
    ON book_copies(book_id, status);

-- The FIFO queue order, oldest first.
CREATE INDEX IF NOT EXISTS idx_waitlist_fifo
    ON waitlist_reservations(book_id, created_at ASC, reservation_id ASC)
    WHERE status = 'Waiting';

-- A student can hold only one waiting spot per title.
CREATE UNIQUE INDEX IF NOT EXISTS idx_unique_active_waitlist_per_user
    ON waitlist_reservations(book_id, user_id)
    WHERE status = 'Waiting';

-- A student's current loans.
CREATE INDEX IF NOT EXISTS idx_active_loans_user
    ON circulation_loans(user_id)
    WHERE return_date IS NULL;

-- A student's acquisition requests.
CREATE INDEX IF NOT EXISTS idx_book_requests_user
    ON book_requests(user_id, status);

-- Supabase publishes the public schema through an automatic REST API. Row Level Security with no
-- policies closes that door, password hashes included. The app connects as the tables' owner,
-- which RLS doesn't restrict, and the Supabase dashboard can still read everything.
ALTER TABLE users ENABLE ROW LEVEL SECURITY;
ALTER TABLE books ENABLE ROW LEVEL SECURITY;
ALTER TABLE book_copies ENABLE ROW LEVEL SECURITY;
ALTER TABLE circulation_loans ENABLE ROW LEVEL SECURITY;
ALTER TABLE return_requests ENABLE ROW LEVEL SECURITY;
ALTER TABLE waitlist_reservations ENABLE ROW LEVEL SECURITY;
ALTER TABLE book_requests ENABLE ROW LEVEL SECURITY;
ALTER TABLE db_audit_logs ENABLE ROW LEVEL SECURITY;
